-- 1. TABLE MEMORY (per table)
SELECT TABLE_NAME,
       RECORD_COUNT,
       MEMORY_SIZE_IN_TOTAL / 1024.0 AS TOTAL_KB,
       MEMORY_SIZE_IN_MAIN / 1024.0 AS MAIN_KB,
       MEMORY_SIZE_IN_DELTA / 1024.0 AS DELTA_KB,
       LAST_COMPRESSED_RECORD_COUNT
FROM M_CS_TABLES
WHERE SCHEMA_NAME = 'TENDER_MONITOR'
ORDER BY MEMORY_SIZE_IN_TOTAL DESC;

-- 2. SERVICE MEMORY (per HANA service)
SELECT SERVICE_NAME,
       HEAP_MEMORY_ALLOCATED_SIZE / 1024.0 / 1024.0 AS HEAP_ALLOC_MB,
       HEAP_MEMORY_USED_SIZE / 1024.0 / 1024.0 AS HEAP_USED_MB,
       TOTAL_MEMORY_USED_SIZE / 1024.0 / 1024.0 AS TOTAL_USED_MB
FROM M_SERVICE_MEMORY
ORDER BY TOTAL_MEMORY_USED_SIZE DESC;

-- 3. ACTIVE CONNECTIONS
SELECT CONNECTION_ID,
       USER_NAME,
       CLIENT_HOST,
       CONNECTION_TYPE,
       CONNECTION_STATUS,
       START_TIME
FROM M_CONNECTIONS
WHERE CONNECTION_STATUS = 'RUNNING'
ORDER BY START_TIME DESC;

-- 4. SYSTEM OVERVIEW (one-query health check)
SELECT SECTION, NAME, STATUS, VALUE
FROM M_SYSTEM_OVERVIEW
ORDER BY SECTION, NAME;

-- 5. DISK USAGE
SELECT PATH,
       USAGE_TYPE,
       FILESYSTEM_TYPE,
       USED_SIZE / 1024.0 / 1024.0 / 1024.0 AS USED_GB,
       TOTAL_SIZE / 1024.0 / 1024.0 / 1024.0 AS TOTAL_GB
FROM M_DISKS
ORDER BY USAGE_TYPE;

-- 6. EXPENSIVE STATEMENTS (requires trace enabled)
SELECT DB_USER,
       SCHEMA_NAME,
       OPERATION,
       DURATION_MICROSEC / 1000.0 AS DURATION_MS,
       CPU_TIME / 1000.0 AS CPU_MS,
       MEMORY_SIZE / 1024.0 AS MEMORY_KB,
       STATEMENT_STRING
FROM M_EXPENSIVE_STATEMENTS
ORDER BY DURATION_MICROSEC DESC
LIMIT 10;

-- Enable the expensive statements trace
ALTER SYSTEM ALTER CONFIGURATION ('indexserver.ini', 'DATABASE')
SET ('expensive_statement', 'enable') = 'true'
WITH RECONFIGURE;

-- 7. SQL PLAN CACHE
SELECT USER_NAME,
       SCHEMA_NAME,
       STATEMENT_HASH,
       IS_VALID,
       STATEMENT_STRING
FROM M_SQL_PLAN_CACHE
WHERE USER_NAME = 'DBADMIN'
ORDER BY STATEMENT_HASH
LIMIT 20;

-- 8. CASE SENSITIVITY DEMONSTRATION
-- Returns 0 (case-sensitive)
SELECT COUNT(*) FROM TENDER_MONITOR.RECENT_AWARDS
WHERE SUPPLIER_NAME LIKE '%a%';

-- Returns 81 (case-insensitive)
SELECT COUNT(*) FROM TENDER_MONITOR.RECENT_AWARDS
WHERE UPPER(SUPPLIER_NAME) LIKE '%A%';